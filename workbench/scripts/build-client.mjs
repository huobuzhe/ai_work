// 表格工作台 client bundle 打包：client/index.js → client/client.js
// 形状照抄本机一手范例 dsh-pocket/client/build.mjs 与 dsh-prompt-enhancer/scripts/build-client.mjs：
// DSH Web client 的模块系统用 window.__ModuleLoader__.load({id, factory}) 装载浏览器半侧 bundle。
// 本 tracer bullet 的 source 无外部 import / 无 JSX，故不需要 esbuild，直接包进 loader 信封即可。
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptsDir, '..');
const sourcePath = resolve(packageRoot, 'client', 'index.js');
const outputPath = resolve(packageRoot, 'client', 'client.js');
const loaderId = 'dsh-workbench';

const source = await readFile(sourcePath, 'utf8');

const bundled = `/* GENERATED by scripts/build-client.mjs — do not edit by hand. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(loaderId)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${source}
    return module.exports;
  }
});
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, bundled, 'utf8');
console.log(`Wrote ${outputPath}`);
